def detect_and_draw_dimensions(image_path, model_path):
    # Load mô hình đã train 2 class
    model = YOLO(model_path)

    img = cv2.imread(image_path)
    if img is None:
        print("Không thể đọc ảnh. Kiểm tra lại đường dẫn!")
        return

    # Chạy suy luận (tăng imgsz=640 để đồng bộ với lúc train)
    results = model(img, conf=0.5, imgsz=640)

    for r in results:
        for box in r.boxes:
            class_id = int(box.cls[0])
            class_names = ['Orange', 'Non-Orange']
            label_name = class_names[class_id]

            # Đổi màu linh hoạt: Cam = Xanh lá, Không phải cam = Đỏ
            color = (0, 255, 0) if class_id == 0 else (0, 0, 255)

            x1, y1, x2, y2 = map(int, box.xyxy[0])
            width_px = x2 - x1
            height_px = y2 - y1

            # 1. Vẽ bounding box
            cv2.rectangle(img, (x1, y1), (x2, y2), color, 2)

            # 2. Vẽ nhãn thông tin
            text = f"{label_name} - W:{width_px}px H:{height_px}px"
            (text_width, text_height), baseline = cv2.getTextSize(text, cv2.FONT_HERSHEY_SIMPLEX, 0.6, 2)

            # SỬA LỖI: Vẽ nền text khớp với màu của class (color)
            cv2.rectangle(img, (x1, y1 - text_height - 10), (x1 + text_width, y1), color, -1)

            # Viết text (Dùng chữ trắng trên nền tối, chữ đen trên nền sáng để nổi bật)
            text_color = (255, 255, 255) if class_id == 1 else (0, 0, 0)
            cv2.putText(img, text, (x1, y1 - 5), cv2.FONT_HERSHEY_SIMPLEX, 0.6, text_color, 2)

    # 3. Lưu ảnh (Sửa lỗi nối chuỗi đường dẫn)
    output_folder = '/content/drive/MyDrive/OrangeSizeModel/output'
    os.makedirs(output_folder, exist_ok=True)
    output_path = os.path.join(output_folder, 'result_' + os.path.basename(image_path))
    cv2.imwrite(output_path, img)

    # Hiển thị
    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    plt.figure(figsize=(10, 10))
    plt.imshow(img_rgb)
    plt.axis('off')
    plt.show()

